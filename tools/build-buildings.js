// Builds data/buildings.js from OpenStreetMap.
//
//   node tools/build-buildings.js             fetches from the Overpass API
//   node tools/build-buildings.js saved.json  uses a saved Overpass response
//
// Every building footprint in a box around downtown Toronto, in the same
// metres-from-origin frame as data/shoreline.js. Each building records WHERE
// its height came from, so the page can tell measured from estimated:
//   'h'  the OSM "height" tag (metres)
//   'l'  estimated: "building:levels" x LEVEL_HEIGHT
//   'n'  no height information in OSM; drawn at DEFAULT_HEIGHT
// Data (c) OpenStreetMap contributors, ODbL.
const fs = require('fs');
const path = require('path');

const BOX = { s: 43.634, w: -79.410, n: 43.662, e: -79.350 };
const ORIGIN = { lat: 43.635, lon: -79.378 }; // must match build-shoreline.js
const LEVEL_HEIGHT = 3.2;   // metres per storey: an assumption, not a measurement
const DEFAULT_HEIGHT = 6;   // metres, for buildings with no height data
const MIN_AREA = 30;        // m2; smaller footprints (sheds, kiosks) are skipped
// The CN Tower is drawn separately as a marker, so its footprint is left out.
const SKIP_RADIUS = 60; // metres: also drops the tower's separately mapped legs and pod
const SKIP_AT = [{ lat: 43.6426, lon: -79.3871, why: 'CN Tower' }];

const b = `${BOX.s},${BOX.w},${BOX.n},${BOX.e}`;
const QUERY = `[out:json][timeout:120];(way["building"](${b});way["building:part"](${b});relation["building"]["type"="multipolygon"](${b}););out tags geom;`;

const MX = Math.cos(ORIGIN.lat * Math.PI / 180) * 111320, MY = 110574;
const project = p => [(p.lon - ORIGIN.lon) * MX, (p.lat - ORIGIN.lat) * MY];

async function load() {
  if (process.argv[2]) return JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
  const res = await fetch('https://overpass-api.de/api/interpreter', {
    method: 'POST',
    headers: { 'Content-Type': 'application/x-www-form-urlencoded', 'User-Agent': 'static-site-builder/1.0' },
    body: 'data=' + encodeURIComponent(QUERY)
  });
  if (!res.ok) throw new Error('Overpass returned ' + res.status);
  return res.json();
}

function metres(v) {
  if (v == null) return null;
  const n = parseFloat(String(v).replace(',', '.'));
  if (!isFinite(n) || n <= 0) return null;
  return /'|ft|feet/i.test(v) ? n * 0.3048 : n;
}
function area(r) {
  let a = 0;
  for (let i = 0, j = r.length - 1; i < r.length; j = i++) a += (r[j][0] + r[i][0]) * (r[j][1] - r[i][1]);
  return Math.abs(a / 2);
}
function inside(p, r) {
  let c = false;
  for (let i = 0, j = r.length - 1; i < r.length; j = i++) {
    const a = r[i], q = r[j];
    if ((a[1] > p[1]) !== (q[1] > p[1]) && p[0] < (q[0] - a[0]) * (p[1] - a[1]) / (q[1] - a[1]) + a[0]) c = !c;
  }
  return c;
}

(async () => {
  const json = await load();
  const skipPts = SKIP_AT.map(project);
  const counts = { h: 0, l: 0, n: 0 };
  const skipped = { small: 0, open: 0, named: 0, part: 0 };
  const items = [];

  function add(geometry, tags) {
    if (!geometry || geometry.length < 4) { skipped.open++; return; }
    const f = geometry[0], l = geometry[geometry.length - 1];
    if (f.lat !== l.lat || f.lon !== l.lon) { skipped.open++; return; }
    const ring = geometry.slice(0, -1).map(project);
    if (area(ring) < MIN_AREA) { skipped.small++; return; }
    const cx = ring.reduce((s, p) => s + p[0], 0) / ring.length, cy = ring.reduce((s, p) => s + p[1], 0) / ring.length;
    if (skipPts.some(p => inside(p, ring) || Math.hypot(p[0] - cx, p[1] - cy) < SKIP_RADIUS)) { skipped.named++; return; }
    let kind = 'n', h = DEFAULT_HEIGHT;
    const th = metres(tags.height), tl = metres(tags['building:levels']);
    if (th) { kind = 'h'; h = th; }
    else if (tl) { kind = 'l'; h = tl * LEVEL_HEIGHT; }
    if (kind === 'n' && tags['building:part']) { skipped.part++; return; } // a part with no height adds nothing
    counts[kind]++;
    const flat = [];
    for (const p of ring) flat.push(Math.round(p[0] * 10) / 10, Math.round(p[1] * 10) / 10);
    items.push([kind, Math.round(h * 10) / 10, flat]);
  }

  for (const e of json.elements) {
    const tags = e.tags || {};
    if (e.type === 'way') add(e.geometry, tags);
    else if (e.type === 'relation')
      for (const m of e.members || []) if (m.type === 'way' && m.role === 'outer') add(m.geometry, tags);
  }

  const data = {
    source: 'OpenStreetMap contributors (ODbL), building footprints',
    osmTimestamp: json.osm3s && json.osm3s.timestamp_osm_base,
    origin: ORIGIN, box: BOX,
    levelHeight: LEVEL_HEIGHT, defaultHeight: DEFAULT_HEIGHT,
    counts, items
  };
  const out = path.join(__dirname, '..', 'data', 'buildings.js');
  fs.writeFileSync(out,
    '// Generated by tools/build-buildings.js. Do not edit by hand.\n' +
    '// Footprints (c) OpenStreetMap contributors, ODbL. [heightSource, metres, [east, north, ...]]\n' +
    'window.YP = window.YP || {};\nYP.BUILDINGS = ' + JSON.stringify(data) + ';\n');
  const tallest = items.slice().sort((a, c) => c[1] - a[1]).slice(0, 5).map(i => i[0] + ':' + i[1]);
  console.log('buildings:', items.length, counts, '| skipped:', skipped, '| tallest:', tallest.join(' '),
    '| size KB:', Math.round(fs.statSync(out).size / 1024), '| osm base:', data.osmTimestamp);
})().catch(e => { console.error(e); process.exit(1); });
