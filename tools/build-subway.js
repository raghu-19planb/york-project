// Writes data/subway.js: the TTC's rapid transit lines, their stations in order, and the path of each track.
//
//   1. Save an Overpass API answer for this query to a file (the public servers are sometimes busy; try again):
//        [out:json][timeout:90];
//        relation["type"="route"]["route"~"^(subway|light_rail)$"](43.55,-79.70,43.92,-79.10)->.r;
//        .r out geom;
//        node(r.r);
//        out body qt;
//   2. node tools/build-subway.js that-file.json
//
// Everything here is as OpenStreetMap had it on the day of the query: which lines exist, their colours, the
// stations and their order, and where the track runs. Nothing is added. Two things are worked out from it:
// a station counts as a place to change lines when a station of another line is within 300 m, and the first and
// last stations of a line are its ends. Metres from the site's origin: [east, north].
const fs = require('fs'), path = require('path');
const src = process.argv[2]; if (!src) { console.error('usage: node tools/build-subway.js overpass.json'); process.exit(1); }
const j = JSON.parse(fs.readFileSync(src, 'utf8'));
const ORIGIN = { lat: 43.635, lon: -79.378 };
const xy = (lat, lon) => [Math.round((lon - ORIGIN.lon) * Math.cos(ORIGIN.lat * Math.PI / 180) * 111320), Math.round((lat - ORIGIN.lat) * 110574)];
const dist = (a, b) => Math.hypot(a[0] - b[0], a[1] - b[1]);
const nodes = new Map(j.elements.filter(e => e.type === 'node').map(n => [n.id, n]));
const lines = [];
for (const r of j.elements.filter(e => e.type === 'relation').sort((a, b) => a.id - b.id)) {
  const t = r.tags || {}; if (lines.some(l => l.ref === t.ref)) continue; // one direction of each line is enough
  const stops = r.members.filter(m => m.type === 'node' && /^stop/.test(m.role || '')).map(m => { const n = nodes.get(m.ref); return n && n.tags && n.tags.name ? { name: n.tags.name.replace(/ Station$/, ''), at: xy(n.lat, n.lon) } : null; }).filter(Boolean);
  if (stops.length < 2) continue;
  // the track: the member ways joined end to end, turned round where needed; if they do not join, the stations are joined directly
  const ways = r.members.filter(m => m.type === 'way' && !m.role && m.geometry).map(m => m.geometry.map(p => xy(p.lat, p.lon)));
  let track = [], joined = ways.length > 0;
  for (const w of ways) {
    if (!track.length) { track = w.slice(); continue; }
    const end = track[track.length - 1], a = dist(end, w[0]), b = dist(end, w[w.length - 1]);
    if (Math.min(a, b) > 120) { // the first way may itself be the wrong way round
      if (track.length === ways[0].length && Math.min(dist(track[0], w[0]), dist(track[0], w[w.length - 1])) <= 120) { track.reverse(); const e2 = track[track.length - 1]; track.push(...(dist(e2, w[0]) <= dist(e2, w[w.length - 1]) ? w : w.slice().reverse())); continue; }
      joined = false; break;
    }
    track.push(...(a <= b ? w : w.slice().reverse()));
  }
  if (joined && dist(track[0], stops[0].at) > dist(track[track.length - 1], stops[0].at)) track.reverse();
  if (joined && Math.max(...stops.map(s => Math.min(...track.map(p => dist(p, s.at))))) > 400) joined = false; // a station far from the joined track means the ways were not the whole line
  if (!joined) track = stops.map(s => s.at);
  // thin the track to a point every 40 m or so
  const thin = [track[0]]; for (const p of track) if (dist(p, thin[thin.length - 1]) >= 40) thin.push(p); if (dist(thin[thin.length - 1], track[track.length - 1]) > 1) thin.push(track[track.length - 1]);
  lines.push({ ref: t.ref, name: (t.name || '').replace(/\s*\(.*\)$/, ''), kind: t.route === 'light_rail' ? 'Light rail' : 'Subway', colour: t.colour || '#555555', from: stops[0].name, to: stops[stops.length - 1].name, trackFromMap: joined, stops, track: thin });
}
lines.sort((a, b) => a.ref.localeCompare(b.ref, 'en', { numeric: true }));
for (const l of lines) l.stops.forEach((s, i) => {
  s.end = i === 0 || i === l.stops.length - 1;
  s.change = lines.filter(o => o !== l && o.stops.some(q => dist(q.at, s.at) <= 300)).map(o => o.ref);
});
const out = `// Generated by tools/build-subway.js. Do not edit by hand.
// © OpenStreetMap contributors, ODbL. As mapped on ${(j.osm3s && j.osm3s.timestamp_osm_base || '').slice(0, 10)}. Metres from origin: [east, north].
window.YP = window.YP || {};
YP.SUBWAY = ${JSON.stringify({ origin: ORIGIN, source: 'OpenStreetMap contributors (ODbL)', sourceUrl: 'https://www.openstreetmap.org/copyright', osmTimestamp: j.osm3s && j.osm3s.timestamp_osm_base, lines })};
`;
fs.writeFileSync(path.join(__dirname, '..', 'data', 'subway.js'), out);
for (const l of lines) console.log('Line', l.ref, l.name, '|', l.kind, l.colour, '|', l.stops.length, 'stations |', l.trackFromMap ? 'track from the map, ' + l.track.length + ' points' : 'TRACK NOT JOINED: stations joined directly', '| changes:', l.stops.filter(s => s.change.length).map(s => s.name + '→' + s.change.join('+')).join(', '));
console.log('wrote data/subway.js', Math.round(out.length / 1024) + ' KB');
